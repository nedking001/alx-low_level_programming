#include <stdio.h>
/**
 * add - add 2 integers
 * @a: 1st integer
 * @b: 2nd integer
 * Return: addition
 */

int add(int a, int b)
{
	return (a + b);
}
/**
 * sub - subtracts 2 integers
 * @a: 1st integer
 * @b: 2nd integer
 * Return: subtraction
 */

int sub(int a, int b)
{
	return (a - b);
}

/**
 * div - divide 2 integers
 * @a: 1st integer
 * @b: 2nd integer
 * Return: Quotient
 */

int div(int a, int b)
{
	return (a / b);
}

/**
 * mul - product of 2 integers
 * @a: 1st integer
 * @b: 2nd integer
 * Return: product
 */

int mul(int a, int b)
{
	return (a * b);
}

/**
 * mod - modulus of 2 integers
 * @a: 1st integer
 * @b: 2nd integer
 * Return: modulus
 */

int mod(int a, int b)
{
	return (a % b);
}
